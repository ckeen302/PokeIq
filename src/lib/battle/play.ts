// ---------------------------------------------------------------------------
// Choices
// ---------------------------------------------------------------------------

/**
 * A choice in the simulator's own syntax: "move 1", "move 2 terastallize",
 * "move 3 -1, switch 4", "switch 2", "team 312456", "pass". The simulator
 * decides whether it is legal.
 */
export const BATTLE_CHOICE_RE = /^[a-z0-9 ,-]{1,120}$/;

// ---------------------------------------------------------------------------
// The simulator's request (what a side must answer), as the client reads it
// ---------------------------------------------------------------------------

export interface BattleRequestMove {
  move: string;
  id: string;
  pp?: number;
  maxpp?: number;
  target?: string;
  disabled?: string | boolean;
}

export interface BattleRequestActive {
  moves: BattleRequestMove[];
  trapped?: boolean;
  maybeTrapped?: boolean;
  maybeDisabled?: boolean;
  maybeLocked?: boolean;
  canTerastallize?: string;
  canMegaEvo?: boolean;
  /** Per move: its Z-Move, or null. */
  canZMove?: ({ move: string; target: string } | null)[];
  canDynamax?: boolean;
  maxMoves?: { maxMoves: { move: string; target: string; disabled?: boolean }[] };
}

export interface BattleRequestPokemon {
  ident: string;
  details: string;
  condition: string;
  active: boolean;
  stats: Record<"atk" | "def" | "spa" | "spd" | "spe", number>;
  moves: string[];
  baseAbility: string;
  item: string;
  pokeball: string;
  ability?: string;
  commanding?: boolean;
  reviving?: boolean;
  teraType?: string;
  terastallized?: string;
}

export interface BattleRequest {
  wait?: boolean;
  teamPreview?: boolean;
  forceSwitch?: boolean[];
  active?: BattleRequestActive[];
  maxChosenTeamSize?: number;
  side: { name: string; id: "p1" | "p2"; pokemon: BattleRequestPokemon[] };
  noCancel?: boolean;
  update?: boolean;
}

// ---------------------------------------------------------------------------
// What a player's screen receives
// ---------------------------------------------------------------------------

export type BattleKind = "cpu" | "pvp";
/** normal: someone won (or a tie). forfeit: a player gave up. timeout: ran out the clock. left: disconnected. nocontest: the battle couldn't go on. */
export type BattleEndReason = "normal" | "forfeit" | "timeout" | "left" | "nocontest";

export interface BattleEnd {
  reason: BattleEndReason;
  /** The winner's seat (0 is p1), or null for a tie or no contest. */
  winner: 0 | 1 | null;
  at: number;
}

export interface BattleClockView {
  /** Time left in the bank. */
  bank: number;
  /** Server time this turn's choice is due, while one is owed. */
  deadline: number | null;
}

export interface BattlePlayerView extends DuelPlayerView {
  /** In the lobby of a bring-your-own-team format: whether a team is in. */
  hasTeam: boolean;
}

export interface BattleView {
  code: string;
  kind: BattleKind;
  format: PlayFormatId;
  status: DuelStatus;
  /** Server clock. */
  now: number;
  /** Increases with every change, so a slow response never overwrites a newer one. */
  rev: number;
  /** Your seat (0 plays as p1), or null for a visitor. */
  you: 0 | 1 | null;
  players: BattlePlayerView[];
  cpu?: { level: CpuLevel };
  turn: number;
  /**
   * Your channel of the battle protocol (hidden information already split
   * out): lines `from` to `total` (exclusive). Poll with ?since=total.
   */
  log: { from: number; total: number; lines: string[] };
  /** The choice the simulator wants from you now, with the counter that must come back with it. */
  request: { rqid: number; data: BattleRequest } | null;
  /** You've chosen; the opponent hasn't yet. */
  waiting: boolean;
  /** Live battles: both clocks (yours first). */
  clocks?: { you: BattleClockView; foe: BattleClockView };
  end?: BattleEnd;
  /** Once either player asks for a rematch: the new battle's code. */
  rematch?: string;
  /** Live battles: the players' chat, oldest first. */
  chat?: ChatLine[];
  /** Custom rules: the ruleset, with its name ("[Gen 4] Custom · Lv 50"). */
  rules?: CustomRules;
  /** The format's name as the players see it, where it isn't PLAY_FORMAT_INFO's. */
  formatName?: string;
  /** Live battles: the turn timer (null: off). */
  timer?: { bank: number; perTurn: number; cap: number } | null;
}

/** Creating, joining or rematching a battle: its code, your seat's token and the battle. */
export interface BattleSeatResponse {
  code: string;
  token: string;
  view: BattleView;
}

/** Where each kind of battle is played. */
export const battleHref = (kind: BattleKind, code: string) => (kind === "cpu" ? `/battle/play/${code}` : `/battle/live/${code}`);
