/** Showdown's game types: how many Pokémon a side has out, and how many trainers battle. */
export type GameType = "singles" | "doubles" | "triples" | "freeforall" | "multi";

/** Trainers in a battle: four in Free-For-All and Multi Battles, two otherwise. */
export const playerCount = (gameType: GameType) => (gameType === "freeforall" || gameType === "multi" ? 4 : 2);
/** Pokémon out at once per trainer. */
export const activesPerSide = (gameType: GameType) => (gameType === "triples" ? 3 : gameType === "doubles" ? 2 : 1);
/** Pokémon out at once on each half of the field (Showdown's activePerHalf): a Multi or Free-For-All half holds two trainers' Pokémon. */
export const activesPerHalf = (gameType: GameType) => (playerCount(gameType) === 4 ? 2 : activesPerSide(gameType));
/** Multi Battles: seats 0 and 2 (p1 and p3) battle together, as do seats 1 and 3. */
export const teamOf = (gameType: GameType, seat: number) => (gameType === "multi" ? seat % 2 : seat);
/** A game type a format id names, when it isn't in PLAY_FORMAT_INFO (Showdown's own formats through custom rules). */
export const isGameType = (v: unknown): v is GameType => v === "singles" || v === "doubles" || v === "triples" || v === "freeforall" || v === "multi";

