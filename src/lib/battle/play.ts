export type BattleKind = "cpu" | "pvp";
/** normal: someone won (or a tie). forfeit: a player gave up. timeout: ran out the clock. left: disconnected. nocontest: the battle couldn't go on. */
export type BattleEndReason = "normal" | "forfeit" | "timeout" | "left" | "nocontest";

export interface BattleEnd {
  reason: BattleEndReason;
  /**
   * The winner's seat (0 is p1), or null for a tie or no contest. A Multi
   * Battle's is the winning team's first seat (0 or 1); `winners` has both.
   */
  winner: number | null;
  /** Four-player battles: every winning seat (both partners in a Multi Battle). */
  winners?: number[];
  /** Free-For-All: every seat from first to last (the winner, then the trainers knocked out, latest first). */
  standings?: number[];
  at: number;
}

export interface BattleClockView {
  /** Time left in the bank. */
  bank: number;
  /** Server time this turn's choice is due, while one is owed. */
  deadline: number | null;
  /** Server time the owed choice was asked for (the timer's messages count from it). */
  startedAt?: number | null;
}

export interface BattlePlayerView extends DuelPlayerView {
  /** In the lobby of a bring-your-own-team format: whether a team is in. */
  hasTeam: boolean;
  /** A seat the computer plays (four-player battles fill empty seats with it). */
  cpu?: boolean;
  /** Free-For-All: knocked out on this turn (their whole team fainted, or they forfeited). */
  out?: number;
  /** Ranked battles: the Glicko-2 rating (and ranked games) this trainer brought. */
  rating?: number;
  games?: number;
  /** Ranked battles: the Elo this trainer brought (the number shown beside their name). */
  elo?: number;
}

/** One seat's ratings before and after a ranked battle: Glicko-2, and Elo (whole numbers) once the ladder has it. */
export interface BattleRatingChange {
  before: number;
  after: number;
  elo?: { before: number; after: number };
}

/** A finished ranked battle: each seat's ratings before and after. */
export type BattleRatings = [BattleRatingChange, BattleRatingChange];

export interface BattleView {
  code: string;
  kind: BattleKind;
  format: PlayFormatId;
  status: DuelStatus;
  /** Server clock. */
  now: number;
  /** Increases with every change, so a slow response never overwrites a newer one. */
  rev: number;
  /** Your seat (0 plays as p1, up to 3 as p4 in four-player battles), or null for a visitor. */
  you: number | null;
  players: BattlePlayerView[];
  /** Showdown's game type for this battle (singles, doubles, triples, freeforall, multi). */
  gameType?: GameType;
  cpu?: { level: CpuLevel };
  turn: number;
  /**
   * Your channel of the battle protocol (hidden information already split
   * out): lines `from` to `total` (exclusive). Poll with ?since=total.
   */
  log: { from: number; total: number; lines: string[] };
  /** The choice the simulator wants from you now, with the counter that must come back with it. */
  request: { rqid: number; data: BattleRequest } | null;
  /** Your choice is in and the opponent's isn't: it can still be cancelled (send `undo` with this rqid). */
  cancel?: { rqid: number };
  /** You've chosen; the opponent hasn't yet. */
  waiting: boolean;
  /** Live battles: both clocks (yours first); four-player battles add every seat's (null for the computer's seats). */
  clocks?: { you: BattleClockView; foe: BattleClockView; seats?: (BattleClockView | null)[] };
  end?: BattleEnd;
  /** Once either player asks for a rematch: the new battle's code. */
  rematch?: string;
  /** Live battles: the players' chat, oldest first. */
  chat?: ChatLine[];
  /** Custom rules: the ruleset, with its name ("[Gen 4] Custom · Lv 50"). */
  rules?: CustomRules;
  /** The format's name as the players see it, where it isn't PLAY_FORMAT_INFO's. */
  formatName?: string;
  /** A Battle Frontier run's battle: where the run stands. */
  frontier?: FrontierBattleInfo;
  /** Live battles: the turn timer (null: off). */
  timer?: BattleTimer | null;
  /** Live battles: running out the clock once loses (else the timer moves for you, and a second timeout loses). */
  timeoutLoses?: boolean;
  /** Live battles with the timer off: either player may start it. */
  timerStartable?: boolean;
  /** Live battles: you asked for the timer, and may turn it off again (Showdown's /timer off). */
  timerStoppable?: boolean;
  /** Live battles: how many spectators are watching right now. */
  spectators?: number;
  /** Live battles: listed in the Watch lobby. */
  public?: boolean;
  /** A ranked ladder battle. */
  ranked?: boolean;
  /** A tournament match: the tournament's id. */
  tournament?: string;
  /** After the end: everything that's recorded has been (ratings, history, any automatic replay). */
  settled?: boolean;
  /** Ranked, once settled: the rating change per seat. */
  ratings?: BattleRatings;
  /** The saved replay's id, once there is one. */
  replay?: string;
  /** When the battle began (server time). */
  startedAt?: number;
  /**
   * Live battles, when Supabase Realtime is set up: where the page subscribes
   * to the battle's "something changed" signal (lib/battle/live.ts). Added by
   * the GET route; absent or null: the page polls.
   */
  live?: { url: string; anon: string; key: JsonWebKey } | null;
}

