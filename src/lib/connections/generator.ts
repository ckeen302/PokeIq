import { Rng } from "@/lib/rng";
import { CATEGORIES, categoryOf, type Category, type CategoryFamily } from "./categories";
import { FACTS, SV, factsOf, type Facts } from "./facts";
import { MIXED_CATEGORIES, linkTiles, patternsFor, tileRef, type TileRef } from "./mixed";
import { isPokemonTile } from "./tiles";
import { CONN_GROUPS, CONN_GROUP_SIZE, CONN_MAX_MISTAKES, guessKey, type ConnGuessKind, type ConnLevel } from "./types";

/**
 * PokéConnections puzzles: four categories, four Pokémon each, built so
 * every one of the 16 Pokémon fits exactly ONE of the four groups
 * (validatePuzzle checks every tile against every group). Seeded and
 * deterministic: the dailies are pre-generated by
 * scripts/connections-dailies.ts, practice puzzles come from the same
 * generator on demand.
 */

export interface PuzzleGroup {
  /** A category id (./categories). */
  category: string;
  members: number[];
}

export interface Puzzle {
  /** Easiest first: index = level (yellow, green, blue, purple). */
  groups: PuzzleGroup[];
  /** The 16 Pokémon in the order the grid starts in. */
  tiles: number[];
}

// ---------------------------------------------------------------------------
// The uniqueness rule
// ---------------------------------------------------------------------------

const slugOf = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "");

/** A move or ability tile that is the exact subject of another group ("Can have Levitate", "Learns Surf"): a technicality. */
function clashesWithTopic(ref: TileRef, cats: readonly Category[]): boolean {
  const prefixes = ref.kind === "ability" ? ["ability:", "hidden:"] : ref.kind === "move" ? ["move:"] : [];
  return cats.some((c) => prefixes.some((p) => c.id.startsWith(p) && slugOf(c.id.slice(p.length)) === slugOf(ref.name)));
}

/**
 * Every reason the puzzle is unfair, or [] when it's fine:
 * - four groups of four, sixteen different Pokémon, one per evolution family;
 * - every tile passes its own group's test and NO other group's (nor the
 *   other groups' guards: no technicalities);
 * - a group about Scarlet & Violet learnsets only beside Pokémon that are in SV;
 * - the grid order is those sixteen.
 * A mixed group's moves, abilities and types are tiles too: each must pass
 * its own group's tile test and no other group's (only mixed groups accept
 * them), and an ability or move can't be the very one another group is about.
 */
export function validatePuzzle(puzzle: { groups: readonly PuzzleGroup[]; tiles?: readonly number[] }): string[] {
  const errors: string[] = [];
  const { groups } = puzzle;
  if (groups.length !== CONN_GROUPS) errors.push(`${groups.length} groups, not ${CONN_GROUPS}`);
  const cats: Category[] = [];
  for (const g of groups) {
    try {
      cats.push(categoryOf(g.category));
    } catch {
      errors.push(`unknown category ${g.category}`);
    }
  }
  if (errors.length) return errors;
  if (new Set(groups.map((g) => g.category)).size !== groups.length) errors.push("a category twice");
  const ids = groups.flatMap((g) => g.members);
  if (groups.some((g) => g.members.length !== CONN_GROUP_SIZE)) errors.push("a group without exactly four Pokémon");
  if (new Set(ids).size !== ids.length) errors.push("a Pokémon twice");
  let facts: Facts[];
  let refs: Map<number, TileRef>;
  try {
    facts = ids.filter(isPokemonTile).map(factsOf);
    refs = new Map(ids.filter((id) => !isPokemonTile(id)).map((id) => [id, tileRef(id)]));
  } catch (err) {
    return [...errors, (err as Error).message];
  }
  if (new Set(facts.map((f) => f.familyKey)).size !== facts.length) errors.push("two Pokémon from one evolution family");
  if (refs.size && !cats.some((c) => c.mixed)) errors.push("a move, ability or type tile outside a mixed group");
  const sv = cats.some((c) => c.needsSV);
  groups.forEach((g, gi) => {
    for (const id of g.members) {
      const ref = refs.get(id);
      if (ref) {
        const fits = cats.filter((c) => c.testTile?.(ref));
        if (!cats[gi].testTile?.(ref)) errors.push(`${ref.name} doesn't fit its own group (${cats[gi].label})`);
        if (fits.length !== 1) errors.push(`${ref.name} fits ${fits.length} groups: ${fits.map((c) => c.label).join(", ")}`);
        if (clashesWithTopic(ref, cats)) errors.push(`${ref.name} is the very ${ref.kind} another group is about`);
        continue;
      }
      const f = factsOf(id);
      const fits = cats.filter((c) => c.test(f));
      if (!cats[gi].test(f)) errors.push(`${f.name} doesn't fit its own group (${cats[gi].label})`);
      if (fits.length !== 1) errors.push(`${f.name} fits ${fits.length} groups: ${fits.map((c) => c.label).join(", ")}`);
      cats.forEach((c, ci) => {
        if (ci !== gi && c.guard?.(f)) errors.push(`${f.name} is too close to ${c.label}`);
      });
      if (sv && f.learnsetGame !== SV) errors.push(`${f.name} isn't in Scarlet & Violet`);
    }
  });
  if (puzzle.tiles && (puzzle.tiles.length !== ids.length || guessKey(puzzle.tiles) !== guessKey(ids))) errors.push("the grid isn't the groups' sixteen Pokémon");
  return errors;
}

// ---------------------------------------------------------------------------
// Playing guesses
// ---------------------------------------------------------------------------

export interface PlayedGuess {
  kind: ConnGuessKind;
  /** The group found, for a correct guess. */
  level?: ConnLevel;
}

export interface PlayState {
  results: PlayedGuess[];
  /** Group levels in the order found. */
  found: ConnLevel[];
  mistakes: number;
  over: boolean;
  won: boolean;
}

/**
 * Plays a game's guesses in order: each is right (a whole group), one away
 * (three of a group) or wrong. A guess the player already made is a
 * "repeat" and costs nothing, as is anything after the game is over.
 * Throws on a guess that isn't four different tiles still on the grid.
 */
export function playGuesses(puzzle: Puzzle, guesses: readonly (readonly number[])[]): PlayState {
  const tiles = new Set(puzzle.tiles);
  const seen = new Set<string>();
  const state: PlayState = { results: [], found: [], mistakes: 0, over: false, won: false };
  for (const guess of guesses) {
    if (guess.length !== CONN_GROUP_SIZE || new Set(guess).size !== CONN_GROUP_SIZE || guess.some((id) => !tiles.has(id))) {
      throw new Error("A guess is four different Pokémon from the grid.");
    }
    const key = guessKey(guess);
    if (state.over || seen.has(key)) {
      state.results.push({ kind: "repeat" });
      continue;
    }
    if (guess.some((id) => state.found.some((lv) => puzzle.groups[lv].members.includes(id)))) {
      throw new Error("That Pokémon's group is already found.");
    }
    seen.add(key);
    const overlaps = puzzle.groups.map((g) => g.members.filter((id) => guess.includes(id)).length);
    const hit = overlaps.indexOf(CONN_GROUP_SIZE);
    if (hit >= 0) {
      state.found.push(hit as ConnLevel);
      state.results.push({ kind: "correct", level: hit as ConnLevel });
    } else {
      state.mistakes++;
      state.results.push({ kind: Math.max(...overlaps) === CONN_GROUP_SIZE - 1 ? "one-away" : "wrong" });
    }
    if (state.found.length === CONN_GROUPS) state.over = state.won = true;
    else if (state.mistakes >= CONN_MAX_MISTAKES) state.over = true;
  }
  return state;
}

// ---------------------------------------------------------------------------
// Red herrings and difficulty
// ---------------------------------------------------------------------------

export interface Herring {
  id: number;
  reason: string;
}

/** The Pokémon from other groups that look like they belong in group `gi`. */
export function herringsOf(puzzle: { groups: readonly PuzzleGroup[] }, gi: number): Herring[] {
  const cat = categoryOf(puzzle.groups[gi].category);
  if (!cat.lure) return [];
  const out: Herring[] = [];
  puzzle.groups.forEach((g, i) => {
    if (i === gi) return;
    for (const id of g.members) {
      if (!isPokemonTile(id)) continue;
      const reason = cat.lure!(factsOf(id));
      if (reason) out.push({ id, reason });
    }
  });
  return out;
}

/** How hard a group plays: its category's difficulty, plus a little for each red herring pointing at it. */
export function groupRating(puzzle: { groups: readonly PuzzleGroup[] }, gi: number): number {
  return categoryOf(puzzle.groups[gi].category).difficulty + 0.2 * Math.min(2, herringsOf(puzzle, gi).length);
}

/** Obvious traits (a type, a generation) four or more tiles share across groups: tempting wrong groups. */
const OBVIOUS = CATEGORIES.filter((c) => c.id.startsWith("type:") || c.id.startsWith("gen:"));

function decoys(groups: readonly PuzzleGroup[]): number {
  const ids = groups.flatMap((g) => g.members).filter(isPokemonTile);
  let n = 0;
  for (const c of OBVIOUS) {
    const hits = ids.filter((id) => c.test(factsOf(id)));
    if (hits.length >= CONN_GROUP_SIZE && !groups.some((g) => hits.every((id) => g.members.includes(id)))) n++;
  }
  return n;
}

/** Higher is a better puzzle: red herrings in most groups, a tempting wrong group or two, but not a pile of them. */
export function scorePuzzle(groups: readonly PuzzleGroup[]): number {
  let herrings = 0;
  let groupsWithHerrings = 0;
  for (let i = 0; i < groups.length; i++) {
    const h = herringsOf({ groups }, i).length;
    herrings += Math.min(2, h);
    if (h) groupsWithHerrings++;
  }
  const d = decoys(groups);
  return herrings + groupsWithHerrings + Math.min(d, 2) * 0.75 - Math.max(0, d - 3) * 0.5;
}

// ---------------------------------------------------------------------------
// Building one
// ---------------------------------------------------------------------------

/** Difficulty bands a puzzle draws one category from each of. */
const BANDS: [number, number][] = [
  [0, 1.75],
  [1.75, 2.45],
  [2.45, 3.15],
  [3.15, 9],
];

/** How often each kind of question comes up (each family shares its weight among its categories). */
const FAMILY_WEIGHT: Record<CategoryFamily, number> = {
  type: 1,
  origin: 1,
  evolution: 1.1,
  battle: 1.1,
  stats: 0.8,
  body: 0.8,
  forms: 0.9,
  breeding: 0.3,
  name: 0.4,
  wordplay: 1.2,
  lore: 1.2,
};

const POOL = FACTS.filter((f) => f.pooled);
const MEMBERS = new Map([...CATEGORIES, ...MIXED_CATEGORIES].map((c) => [c.id, POOL.filter((f) => c.test(f))]));
const FAMILY_SIZE = new Map<string, number>();
for (const c of CATEGORIES) FAMILY_SIZE.set(`${c.family}|${bandOf(c)}`, (FAMILY_SIZE.get(`${c.family}|${bandOf(c)}`) ?? 0) + 1);

function bandOf(c: Category): number {
  return BANDS.findIndex(([lo, hi]) => c.difficulty >= lo && c.difficulty < hi);
}

const count = (p: string, c: string) => p.split(c).length - 1;

function weightedPick<T>(rng: Rng, items: readonly T[], weight: (t: T) => number): T | undefined {
  const total = items.reduce((s, t) => s + weight(t), 0);
  if (total <= 0) return undefined;
  let r = rng.next() * total;
  for (const t of items) {
    r -= weight(t);
    if (r < 0) return t;
  }
  return items[items.length - 1];
}

export interface GenerateOptions {
  /** Categories not to use (the last few days'). */
  avoidCategories?: ReadonlySet<string>;
  /** Categories never to use, however long the search takes (the ones moderators switched off). */
  excludeCategories?: ReadonlySet<string>;
  /** Pokémon not to use (the last few days'). */
  avoidPokemon?: ReadonlySet<number>;
  /** Ways to fill a set of categories before keeping the best (×3 tries). */
  candidates?: number;
  /** Unlimited's difficulty (DIFFICULTY_BANDS); dailies are always normal. */
  difficulty?: ConnDifficulty;
  /**
   * How many groups are mixed (moves, abilities and types beside Pokémon):
   * 0 or 1 or 2, or "seed" to let the seed decide (none, one or two).
   * Left out, none: every puzzle made before mixed groups is unchanged.
   */
  mixed?: 0 | 1 | 2 | "seed";
}

/** Tries to fill four categories with four Pokémon each; null if they don't fit together. */
function fill(rng: Rng, cats: Category[], avoid: ReadonlySet<number>): PuzzleGroup[] | null {
  const sv = cats.some((c) => c.needsSV);
  const usedFamilies = new Set<number>();
  const groups: PuzzleGroup[] = cats.map((c) => ({ category: c.id, members: [] }));
  const eligible = cats.map((c, i) =>
    (MEMBERS.get(c.id) ?? []).filter((f) => !avoid.has(f.id) && (!sv || f.learnsetGame === SV) && cats.every((o, j) => j === i || (!o.test(f) && !o.guard?.(f))))
  );
  // The tightest category first.
  const order = [0, 1, 2, 3].sort((a, b) => eligible[a].length - eligible[b].length);
  for (const i of order) {
    const lureWeight = (f: Facts) => 1 + 2 * cats.filter((o, j) => j !== i && o.lure?.(f)).length;
    let pool = eligible[i].filter((f) => !usedFamilies.has(f.familyKey));
    // A mixed group: some Pokémon, and the rest moves, abilities and the type itself.
    const mixedType = cats[i].mixed ? cats[i].id.slice("mixed:".length) : null;
    const pattern = mixedType ? rng.pick(patternsFor(mixedType)) : null;
    for (let k = 0; k < (pattern ? count(pattern, "P") : CONN_GROUP_SIZE); k++) {
      const f = weightedPick(rng, pool, lureWeight);
      if (!f) return null;
      groups[i].members.push(f.id);
      usedFamilies.add(f.familyKey);
      pool = pool.filter((g) => g.familyKey !== f.familyKey);
    }
    if (mixedType && pattern) {
      const link = linkTiles(mixedType);
      const usable = (ids: number[]) => rng.shuffle(ids.filter((id) => !clashesWithTopic(tileRef(id), cats)));
      const moves = usable(link.moves);
      const abilities = usable(link.abilities);
      for (const c of pattern) {
        if (c === "M") groups[i].members.push(moves.pop()!);
        else if (c === "A") groups[i].members.push(abilities.pop()!);
        else if (c === "T") groups[i].members.push(link.type);
      }
      if (groups[i].members.includes(undefined as unknown as number) || groups[i].members.length !== CONN_GROUP_SIZE) return null;
    }
  }
  return groups;
}

/**
 * Which difficulty band each of a puzzle's four categories comes from.
 * Normal (every daily) takes one from each; Easy two from the easiest and
 * none from the hardest; Hard none from the easiest and two from the hardest.
 */
export const DIFFICULTY_BANDS = {
  easy: [0, 0, 1, 2],
  normal: [0, 1, 2, 3],
  hard: [1, 2, 3, 3],
} as const;
export type ConnDifficulty = keyof typeof DIFFICULTY_BANDS;

function pickCategories(rng: Rng, avoid: ReadonlySet<string>, bands: readonly number[] = DIFFICULTY_BANDS.normal): Category[] | null {
  const cats: Category[] = [];
  for (const band of bands) {
    const options = CATEGORIES.filter((c) => bandOf(c) === band && !avoid.has(c.id) && !cats.some((o) => o.family === c.family));
    const c = weightedPick(rng, options, (c) => FAMILY_WEIGHT[c.family] / (FAMILY_SIZE.get(`${c.family}|${band}`) ?? 1));
    if (!c) return null;
    cats.push(c);
  }
  return cats;
}

/**
 * Swaps the group(s) in the middle bands for mixed ones (in place), unless
 * a type-family group is left beside them. False when it can't.
 */
function withMixed(rng: Rng, cats: Category[], wanted: number, banned: ReadonlySet<string>): boolean {
  const slots = wanted === 1 ? [rng.next() < 0.5 ? 1 : 2] : [1, 2];
  const options = MIXED_CATEGORIES.filter((c) => !banned.has(c.id));
  const chosen: Category[] = [];
  for (const slot of slots) {
    const left = options.filter((o) => !chosen.includes(o));
    if (!left.length) return false;
    const c = rng.pick(left);
    chosen.push(c);
    cats[slot] = c;
  }
  return cats.every((c) => c.mixed || c.family !== "type");
}

/** Orders groups easiest first (by groupRating) and shuffles the sixteen tiles. */
function finish(rng: Rng, groups: PuzzleGroup[]): Puzzle {
  const rated = groups.map((g, i) => ({ g, r: groupRating({ groups }, i) }));
  rated.sort((a, b) => a.r - b.r || a.g.category.localeCompare(b.g.category));
  const ordered = rated.map((x) => ({ category: x.g.category, members: [...x.g.members] }));
  return { groups: ordered, tiles: rng.shuffle(ordered.flatMap((g) => g.members)) };
}

/** A puzzle needs at least this score (scorePuzzle) to be kept, unless nothing better turns up. */
const GOOD_ENOUGH = 4;

/**
 * A puzzle from a seed: the same seed always gives the same puzzle. Picks
 * four categories (one per difficulty band, weighted by family), fills
 * them a number of ways and keeps the best-scored fill (see scorePuzzle).
 * A set of categories that can't make a puzzle with enough red herrings is
 * passed over for another.
 */
export function generatePuzzle(seed: string, options: GenerateOptions = {}): Puzzle {
  const rng = new Rng(`pokeconnections:${seed}`);
  const tries = (options.candidates ?? 12) * 3;
  const wanted = options.mixed === "seed" ? [0, 1, 1, 2][new Rng(`pokeconnections-mixed:${seed}`).int(0, 3)] : (options.mixed ?? 0);
  const none = new Set<never>();
  let fallback: { groups: PuzzleGroup[]; score: number } | null = null;
  for (let set = 0; set < 400; set++) {
    // Late on, let go of the variety rules rather than fail.
    const strict = set < 300;
    const banned = options.excludeCategories ?? none;
    const avoid = strict && options.avoidCategories ? new Set([...options.avoidCategories, ...banned]) : banned;
    const cats = pickCategories(rng, avoid, DIFFICULTY_BANDS[options.difficulty ?? "normal"]);
    if (!cats) continue;
    if (wanted > 0 && !withMixed(rng, cats, wanted, banned)) continue;
    let best: { groups: PuzzleGroup[]; score: number } | null = null;
    for (let i = 0; i < tries; i++) {
      const groups = fill(rng, cats, strict ? (options.avoidPokemon ?? none) : none);
      if (!groups || validatePuzzle({ groups }).length) continue;
      const score = scorePuzzle(groups);
      if (!best || score > best.score) best = { groups, score };
    }
    if (!best) continue;
    if (best.score >= GOOD_ENOUGH) return finish(rng, best.groups);
    if (!fallback || best.score > fallback.score) fallback = best;
  }
  if (!fallback) throw new Error(`No puzzle for seed ${seed}`);
  return finish(rng, fallback.groups);
}
