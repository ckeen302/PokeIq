export interface PlayedGuess {
  kind: ConnGuessKind;
  /** The group found, for a correct guess. */
  level?: ConnLevel;
}

export interface PlayState {
  results: PlayedGuess[];
  /** Group levels in the order found. */
  found: ConnLevel[];
  mistakes: number;
  over: boolean;
  won: boolean;
}

/**
 * Plays a game's guesses in order: each is right (a whole group), one away
 * (three of a group) or wrong. A guess the player already made is a
 * "repeat" and costs nothing, as is anything after the game is over.
 * Throws on a guess that isn't four different tiles still on the grid.
 */
export function playGuesses(puzzle: Puzzle, guesses: readonly (readonly number[])[]): PlayState {
  const tiles = new Set(puzzle.tiles);
  const size = puzzle.groups.length;
  const maxMistakes = connMaxMistakes(size as ConnSize);
  const seen = new Set<string>();
  const state: PlayState = { results: [], found: [], mistakes: 0, over: false, won: false };
  for (const guess of guesses) {
    if (guess.length !== size || new Set(guess).size !== size || guess.some((id) => !tiles.has(id))) {
      throw new Error(`A guess is ${size === 5 ? "five" : "four"} different Pokémon from the grid.`);
    }
    const key = guessKey(guess);
    if (state.over || seen.has(key)) {
      state.results.push({ kind: "repeat" });
      continue;
    }
    if (guess.some((id) => state.found.some((lv) => puzzle.groups[lv].members.includes(id)))) {
      throw new Error("That Pokémon's group is already found.");
    }
    seen.add(key);
    const overlaps = puzzle.groups.map((g) => g.members.filter((id) => guess.includes(id)).length);
    const hit = overlaps.indexOf(size);
    if (hit >= 0) {
      state.found.push(hit as ConnLevel);
      state.results.push({ kind: "correct", level: hit as ConnLevel });
    } else {
      state.mistakes++;
      state.results.push({ kind: Math.max(...overlaps) === size - 1 ? "one-away" : "wrong" });
    }
    if (state.found.length === size) state.over = state.won = true;
    else if (state.mistakes >= maxMistakes) state.over = true;
  }
  return state;
}

// ---------------------------------------------------------------------------
// Red herrings and difficulty
// ---------------------------------------------------------------------------

export interface Herring {
  id: number;
  reason: string;
}

/** The Pokémon from other groups that look like they belong in group `gi`. */
export function herringsOf(puzzle: { groups: readonly PuzzleGroup[] }, gi: number): Herring[] {
  const cat = categoryOf(puzzle.groups[gi].category);
  if (!cat.lure) return [];
  const out: Herring[] = [];
  puzzle.groups.forEach((g, i) => {
    if (i === gi) return;
    for (const id of g.members) {
      if (!isPokemonTile(id)) continue;
      const reason = cat.lure!(factsOf(id));
      if (reason) out.push({ id, reason });
    }
  });
  return out;
}

/** How hard a group plays: its category's difficulty, plus a little for each red herring pointing at it. */
export function groupRating(puzzle: { groups: readonly PuzzleGroup[] }, gi: number): number {
  return categoryOf(puzzle.groups[gi].category).difficulty + 0.2 * Math.min(2, herringsOf(puzzle, gi).length);
}

/** Obvious traits (a type, a generation) MORE tiles than a group share across groups: tempting wrong groups (exactly a group's worth would be a second answer: see secondAnswers). */
const OBVIOUS = CATEGORIES.filter((c) => c.id.startsWith("type:") || c.id.startsWith("gen:"));

function decoys(groups: readonly PuzzleGroup[]): number {
  const ids = groups.flatMap((g) => g.members).filter(isPokemonTile);
  let n = 0;
  for (const c of OBVIOUS) {
    const hits = ids.filter((id) => c.test(factsOf(id)));
    if (hits.length > groups.length && !groups.some((g) => hits.every((id) => g.members.includes(id)))) n++;
  }
  return n;
}

/** Higher is a better puzzle: red herrings in most groups, a tempting wrong group or two, but not a pile of them. */
export function scorePuzzle(groups: readonly PuzzleGroup[]): number {
  let herrings = 0;
  let groupsWithHerrings = 0;
  for (let i = 0; i < groups.length; i++) {
    const h = herringsOf({ groups }, i).length;
    herrings += Math.min(2, h);
    if (h) groupsWithHerrings++;
  }
  const d = decoys(groups);
  return herrings + groupsWithHerrings + Math.min(d, 2) * 0.75 - Math.max(0, d - 3) * 0.5;
}

