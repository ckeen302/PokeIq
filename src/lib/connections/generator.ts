/** Difficulty bands a puzzle draws one category from each of. */
const BANDS: [number, number][] = [
  [0, 1.75],
  [1.75, 2.45],
  [2.45, 3.15],
  [3.15, 9],
];

/** How often each kind of question comes up (each family shares its weight among its categories). */
const FAMILY_WEIGHT: Record<CategoryFamily, number> = {
  type: 1,
  origin: 1,
  evolution: 1.1,
  battle: 1.1,
  stats: 0.8,
  body: 0.8,
  forms: 0.9,
  breeding: 0.3,
  name: 0.4,
  wordplay: 1.2,
  lore: 1.2,
};

const POOL = FACTS.filter((f) => f.pooled);
const MEMBERS = new Map([...CATEGORIES, ...MIXED_CATEGORIES].map((c) => [c.id, POOL.filter((f) => c.test(f))]));
const packMembers = new Map<ConnPack, Map<string, Facts[]>>();

/** Each category's pool members, narrowed to a pack when there is one. */
function membersFor(pack?: ConnPack): Map<string, Facts[]> {
  if (!pack) return MEMBERS;
  let m = packMembers.get(pack);
  if (!m) {
    const ids = packIds(pack);
    m = new Map([...MEMBERS].map(([id, list]) => [id, list.filter((f) => ids.has(f.id))]));
    packMembers.set(pack, m);
  }
  return m;
}

/** A category is usable in a pack when enough different evolution families of the pack pass it. */
const PACK_MIN_FAMILIES = 6;
const familiesIn = (list: readonly Facts[] | undefined) => new Set((list ?? []).map((f) => f.familyKey)).size;

const FAMILY_SIZE = new Map<string, number>();
for (const c of CATEGORIES) FAMILY_SIZE.set(`${c.family}|${bandOf(c)}`, (FAMILY_SIZE.get(`${c.family}|${bandOf(c)}`) ?? 0) + 1);

function bandOf(c: Category): number {
  return BANDS.findIndex(([lo, hi]) => c.difficulty >= lo && c.difficulty < hi);
}

const count = (p: string, c: string) => p.split(c).length - 1;

function weightedPick<T>(rng: Rng, items: readonly T[], weight: (t: T) => number): T | undefined {
  const total = items.reduce((s, t) => s + weight(t), 0);
  if (total <= 0) return undefined;
  let r = rng.next() * total;
  for (const t of items) {
    r -= weight(t);
    if (r < 0) return t;
  }
  return items[items.length - 1];
}

export interface GenerateOptions {
  /** Categories not to use (the last few days'). */
  avoidCategories?: ReadonlySet<string>;
  /** Categories never to use, however long the search takes (the ones moderators switched off). */
  excludeCategories?: ReadonlySet<string>;
  /** Pokémon not to use (the last few days'). */
  avoidPokemon?: ReadonlySet<number>;
  /** Ways to fill a set of categories before keeping the best (×3 tries). */
  candidates?: number;
  /** Unlimited's difficulty (DIFFICULTY_BANDS); dailies are always normal. */
  difficulty?: ConnDifficulty;
  /** A themed pack: every Pokémon comes from it (mixed groups are off, their moves and abilities aren't the pack's). */
  pack?: ConnPack;
  /**
   * How many groups are mixed (moves, abilities and types beside Pokémon):
   * 0 or 1 or 2, or "seed" to let the seed decide (none, one or two).
   * Left out, none: every puzzle made before mixed groups is unchanged.
   */
  mixed?: 0 | 1 | 2 | "seed";
  /** 4 (the default, and every daily) or 5: five groups of five, which also must have exactly one solution (see isUniquelySolvable). */
  size?: ConnSize;
  /** Counts what the search did (for scripts/connections-5x5.ts). */
  stats?: GenStats;
}

export interface GenStats {
  /** Category sets tried. */
  sets: number;
  /** Fills attempted. */
  fills: number;
  /** Fills that were full but unfair (validatePuzzle). */
  invalid: number;
  /** Fair fills thrown out because the grid had another way to split it. */
  ambiguous: number;
}

/** True when the tiles split into groups of exactly one way (solveGrid: every category that fits exactly a group's size of them). */
export function isUniquelySolvable(tiles: readonly number[]): boolean {
  return solveGrid(tiles, 2).length === 1;
}

/** Tries to fill four categories with four Pokémon each; null if they don't fit together. */
function fill(rng: Rng, cats: Category[], avoid: ReadonlySet<number>, members: Map<string, Facts[]> = MEMBERS): PuzzleGroup[] | null {
  const sv = cats.some((c) => c.needsSV);
  const usedFamilies = new Set<number>();
  const groups: PuzzleGroup[] = cats.map((c) => ({ category: c.id, members: [] }));
  const eligible = cats.map((c, i) =>
    (members.get(c.id) ?? []).filter((f) => !avoid.has(f.id) && (!sv || f.learnsetGame === SV) && cats.every((o, j) => j === i || (!o.test(f) && !o.guard?.(f))))
  );
  // The tightest category first.
  const order = cats.map((_, i) => i).sort((a, b) => eligible[a].length - eligible[b].length);
  for (const i of order) {
    const lureWeight = (f: Facts) => 1 + 2 * cats.filter((o, j) => j !== i && o.lure?.(f)).length;
    let pool = eligible[i].filter((f) => !usedFamilies.has(f.familyKey));
    // A mixed group: some Pokémon, and the rest moves, abilities and the type itself.
    const mixedType = cats[i].mixed ? cats[i].id.slice("mixed:".length) : null;
    const pattern = mixedType ? rng.pick(patternsFor(mixedType)) : null;
    for (let k = 0; k < (pattern ? count(pattern, "P") : cats.length); k++) {
      const f = weightedPick(rng, pool, lureWeight);
      if (!f) return null;
      groups[i].members.push(f.id);
      usedFamilies.add(f.familyKey);
      pool = pool.filter((g) => g.familyKey !== f.familyKey);
    }
    if (mixedType && pattern) {
      const link = linkTiles(mixedType);
      const usable = (ids: number[]) => rng.shuffle(ids.filter((id) => !clashesWithTopic(tileRef(id), cats)));
      const moves = usable(link.moves);
      const abilities = usable(link.abilities);
      for (const c of pattern) {
        if (c === "M") groups[i].members.push(moves.pop()!);
        else if (c === "A") groups[i].members.push(abilities.pop()!);
        else if (c === "T") groups[i].members.push(link.type);
      }
      if (groups[i].members.includes(undefined as unknown as number) || groups[i].members.length !== cats.length) return null;
    }
  }
  return groups;
}

/**
 * Which difficulty band each of a puzzle's four categories comes from.
 * Normal (every daily) takes one from each; Easy two from the easiest and
 * none from the hardest; Hard none from the easiest and two from the hardest.
 */
export const DIFFICULTY_BANDS = {
  easy: [0, 0, 1, 2],
  normal: [0, 1, 2, 3],
  hard: [1, 2, 3, 3],
} as const;
export type ConnDifficulty = keyof typeof DIFFICULTY_BANDS;

/** The same for a 5×5 board: a fifth group, drawn from the middle bands (or, on Hard, the top one). */
export const DIFFICULTY_BANDS_5 = {
  easy: [0, 0, 1, 1, 2],
  normal: [0, 1, 1, 2, 3],
  hard: [1, 2, 2, 3, 3],
} as const;

function pickCategories(rng: Rng, avoid: ReadonlySet<string>, bands: readonly number[] = DIFFICULTY_BANDS.normal, members?: Map<string, Facts[]>): Category[] | null {
  const cats: Category[] = [];
  for (const band of bands) {
    const options = CATEGORIES.filter((c) => bandOf(c) === band && !avoid.has(c.id) && !cats.some((o) => o.family === c.family) && (!members || familiesIn(members.get(c.id)) >= PACK_MIN_FAMILIES));
    const c = weightedPick(rng, options, (c) => FAMILY_WEIGHT[c.family] / (FAMILY_SIZE.get(`${c.family}|${band}`) ?? 1));
    if (!c) return null;
    cats.push(c);
  }
  return cats;
}

/**
 * Swaps the group(s) in the middle bands for mixed ones (in place), unless
 * a type-family group is left beside them. False when it can't.
 */
function withMixed(rng: Rng, cats: Category[], wanted: number, banned: ReadonlySet<string>, bands: readonly number[]): boolean {
  // Only a middle-band slot (a mixed group is medium: 1.75 to 2.45), so Easy keeps two easy groups and Hard two tricky ones.
  const middle = bands.map((b, i) => [b, i]).filter(([b]) => b === 1 || b === 2).map(([, i]) => i);
  const slots = wanted === 1 ? [middle[rng.next() < 0.5 ? 0 : 1] ?? middle[0]] : middle.slice(0, 2);
  const options = MIXED_CATEGORIES.filter((c) => !banned.has(c.id));
  const chosen: Category[] = [];
  for (const slot of slots) {
    const left = options.filter((o) => !chosen.includes(o));
    if (!left.length) return false;
    const c = rng.pick(left);
    chosen.push(c);
    cats[slot] = c;
  }
  // A regular type group ("Pure Fire", "Fire/Flying") about the same type as a mixed group would make its tiles ambiguous.
  const mixedTypes = cats.filter((c) => c.mixed).map((c) => c.id.slice("mixed:".length));
  return cats.every((c) => c.mixed || c.family !== "type" || !c.id.split(/[:-]/).slice(1).some((t) => mixedTypes.includes(t)));
}

/** Orders groups easiest first (by groupRating) and shuffles the sixteen tiles. */
function finish(rng: Rng, groups: PuzzleGroup[]): Puzzle {
  const rated = groups.map((g, i) => ({ g, r: groupRating({ groups }, i) }));
  rated.sort((a, b) => a.r - b.r || a.g.category.localeCompare(b.g.category));
  const ordered = rated.map((x) => ({ category: x.g.category, members: [...x.g.members] }));
  return { groups: ordered, tiles: rng.shuffle(ordered.flatMap((g) => g.members)) };
}

/** A puzzle needs at least this score (scorePuzzle) to be kept, unless nothing better turns up (a bigger board, more herrings). */
const GOOD_ENOUGH = 4;
const goodEnough = (size: ConnSize) => (GOOD_ENOUGH * size) / 4;

/**
 * A puzzle from a seed: the same seed always gives the same puzzle. Picks
 * four categories (one per difficulty band, weighted by family), fills
 * them a number of ways and keeps the best-scored fill (see scorePuzzle).
 * A set of categories that can't make a puzzle with enough red herrings is
 * passed over for another.
 */
export function generatePuzzle(seed: string, options: GenerateOptions = {}): Puzzle {
  const rng = new Rng(`pokeconnections:${seed}`);
  const tries = (options.candidates ?? 12) * 3;
  const members = options.pack ? membersFor(options.pack) : undefined;
  const size: ConnSize = options.size ?? 4;
  const stats = options.stats;
  const wanted = options.pack || size === 5 ? 0 : options.mixed === "seed" ? [0, 1, 1, 2][new Rng(`pokeconnections-mixed:${seed}`).int(0, 3)] : (options.mixed ?? 0);
  const none = new Set<never>();
  let fallback: { groups: PuzzleGroup[]; score: number } | null = null;
  for (let set = 0; set < 400; set++) {
    // Late on, let go of the variety rules rather than fail.
    const strict = set < 300;
    const banned = options.excludeCategories ?? none;
    const avoid = strict && options.avoidCategories ? new Set([...options.avoidCategories, ...banned]) : banned;
    const bands = (size === 5 ? DIFFICULTY_BANDS_5 : DIFFICULTY_BANDS)[options.difficulty ?? "normal"];
    const cats = pickCategories(rng, avoid, bands, members);
    if (!cats) continue;
    if (stats) stats.sets++;
    if (wanted > 0 && !withMixed(rng, cats, wanted, banned, bands)) continue;
    let best: { groups: PuzzleGroup[]; score: number } | null = null;
    for (let i = 0; i < tries; i++) {
      const groups = fill(rng, cats, strict ? (options.avoidPokemon ?? none) : none, members);
      if (stats) stats.fills++;
      if (!groups) continue;
      if (validatePuzzle({ groups }).length) {
        if (stats) stats.invalid++;
        continue;
      }
      // A 5×5 board also has to have only one way to split it, whatever the other categories say.
      if (size === 5 && !isUniquelySolvable(groups.flatMap((g) => g.members))) {
        if (stats) stats.ambiguous++;
        continue;
      }
      // Never a lookalike group. Nor a second solution, except in a themed pack: a pack of one generation is so
      // close-knit that some odd split (colours, Egg Groups, highest stats...) nearly always exists; there it costs score.
      const answers = secondAnswers({ groups }, true);
      if (answers.some((a) => !a.startsWith(SECOND_SOLUTION)) || (answers.length && !options.pack)) {
        if (stats) stats.ambiguous++;
        continue;
      }
      const score = scorePuzzle(groups) - (answers.length ? 1.5 : 0);
      if (!best || score > best.score) best = { groups, score };
    }
    if (!best) continue;
    if (best.score >= goodEnough(size)) return finish(rng, best.groups);
    if (!fallback || best.score > fallback.score) fallback = best;
  }
  // A mixed puzzle that can't be built (rare) is an ordinary one rather than an error.
  if (!fallback && wanted > 0) return generatePuzzle(seed, { ...options, mixed: 0 });
  if (!fallback) throw new Error(`No puzzle for seed ${seed}`);
  return finish(rng, fallback.groups);
}
