import { getPokemon } from "@/lib/pokemon/pokedex";
import type { CoverArt, GameCard, GameKind } from "./video-games-types";

/**
 * Every Pokémon video game the Games tab lists: the main series with its
 * paired and third versions, the remakes, the console and handheld spin-offs
 * and the mobile games. Unreleased games aren't listed.
 *
 * Sources: Wikipedia's "List of Pokémon video games" and each game's article
 * (release dates, platforms, developers), the site's own Pokémon Timeline
 * data (src/data/pokemon-timeline.json) and Serebii's game sections (version
 * exclusives, Legendary Pokémon, box art). A field that couldn't be confirmed
 * is left out rather than guessed.
 *
 * `gen` is the generation for a main-series game, and for a spin-off the
 * generation whose games were current when it came out (as Bulbapedia files
 * them). `released` is the first release anywhere; `firstIn` says where when
 * that wasn't a worldwide launch.
 */
export interface VideoGame {
  slug: string;
  name: string;
  kind: GameKind;
  gen: number;
  released: string;
  /** Where the first release was, when it wasn't worldwide ("Japan"). */
  firstIn?: string;
  /** A note on the first release ("as Red and Green"). */
  releasedAs?: string;
  /** Short label for cards. */
  platform: string;
  /** Every platform, in full, for the game page. */
  platforms: string[];
  developer?: string;
  /** The region (or setting) the game takes place in. */
  region?: string;
  /** One or two sentences: what the game is. */
  summary: string;
  cover: CoverArt;
  /** Games that are grouped together for "Related games" (main series, Mystery Dungeon, Rumble…). */
  series: string;
  /** public/geo/maps/<map>.webp behind the hero. */
  map?: string;
  /** The region's list in Places (/pokedex/places?region=…). */
  placesRegion?: string;
  /** The game's page in Trainers (/pokedex/trainers/<key>). */
  trainers?: string;
  starters?: number[];
  /** Legendary and Mythical Pokémon you can catch in the game (no event distributions). */
  legendaries?: number[];
  exclusives?: [{ version: string; ids: number[] }, { version: string; ids: number[] }];
  whatsNew?: { title: string; text: string }[];
  dlc?: { name: string; released: string; text: string }[];
}

/** Two box covers: public/games/<slug>.webp and <slug>-2.webp. */
const two = (slug: string, a: string, b: string): CoverArt => ({ kind: "box", files: [`${slug}.webp`, `${slug}-2.webp`], alts: [`Pokémon ${a} box art`, `Pokémon ${b} box art`] });
const one = (slug: string, alt: string): CoverArt => ({ kind: "box", files: [`${slug}.webp`], alts: [alt] });
const art = (id: number, alt: string): CoverArt => ({ kind: "art", id, alt, types: (getPokemon(id)?.types as string[] | undefined) ?? ["normal"] });

