#!/usr/bin/env node
// Writes src/app/[locale]: one small file per English page (and per layout, loading, not-found or share image), which
// serves that page at /<lang>/<path> through src/i18n/mirror.tsx. English pages stay exactly where they are.
//   node scripts/i18n/mirror.mjs           write the files
//   node scripts/i18n/mirror.mjs --check   fail if they are out of date (CI)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const APP = "src/app";
const OUT = join(APP, "[locale]");
/** English-only areas: never served in another language. */
const SKIP = [/^admin(\/|$)/, /^api(\/|$)/, /^\[locale\](\/|$)/, /^battle\/player(\/|$)/];
/** Files of the mirror itself, not generated (the language's root layout and 404). */
const OWN = new Set(["layout.tsx", "not-found.tsx"]);
/**
 * Every file under src/app/[locale] is named <name>.locale.tsx: next.config adds "locale.tsx" to pageExtensions only
 * while a language besides English is live, so an English-only build has no language routes at all (its pages,
 * chunks and render types are exactly those of the site without languages).
 */
const out = (rel) => rel.replace(/\.tsx?$/, (ext) => `.locale${ext}`);
const HEADER = "// Generated by scripts/i18n/mirror.mjs (npm run i18n:mirror). Do not edit.";
/** Route segment options Next reads from the file itself, copied as written. */
const COPIED = ["dynamic", "revalidate", "runtime", "maxDuration", "fetchCache", "preferredRegion"];

function walk(dir, rel = "") {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const r = rel ? `${rel}/${name}` : name;
    if (SKIP.some((re) => re.test(r))) continue;
    if (statSync(full).isDirectory()) out.push(...walk(full, r));
    else out.push(r);
  }
  return out;
}

function exportsOf(src) {
  const consts = {};
  for (const key of [...COPIED, "dynamicParams"]) {
    const m = new RegExp(`^export const ${key}\\s*=\\s*([^;\\n]+);?`, "m").exec(src);
    if (m) consts[key] = m[1].trim();
  }
  return {
    consts,
    hasStaticParams: /^export (async )?function generateStaticParams\b|^export const generateStaticParams\b/m.test(src),
    client: /^["']use client["']/.test(src),
  };
}

const base = (rel) => rel.split("/").pop();

function routeOf(relDir) {
  return "/" + relDir.split("/").filter(Boolean).join("/");
}

function pageFile(rel, src) {
  const relDir = dirname(rel) === "." ? "" : dirname(rel);
  const route = relDir ? routeOf(relDir) : "/";
  const { consts, hasStaticParams, client } = exportsOf(src);
  const open = consts.dynamicParams === "true";
  const dynamicSegments = /\[/.test(relDir);
  const imp = `@/app/${rel.replace(/\.tsx?$/, "")}`;
  const image = imageOf(relDir);
  const opts = [...(open ? ["openParams: true"] : []), ...(image ? [`image: ${image}`] : [])];
  const lines = [HEADER, `// Source: src/app/${rel}`];
  if (client) {
    // A client page has no metadata or params of its own: the language's layout checks the language.
    lines.push(`import Source from "${imp}";`, `import { mirrorPage } from "@/i18n/mirror";`, "");
    lines.push(`const m = mirrorPage(${JSON.stringify(route)}, { default: Source });`);
  } else {
    lines.push(`import * as Source from "${imp}";`, `import { mirrorPage } from "@/i18n/mirror";`, "");
    lines.push(`const m = mirrorPage(${JSON.stringify(route)}, Source${opts.length ? `, { ${opts.join(", ")} }` : ""});`);
  }
  lines.push("");
  for (const key of COPIED) if (consts[key] !== undefined) lines.push(`export const ${key} = ${consts[key]};`);
  // Unlisted params of a page that lists them all are 404s, as in English; pages without params are prerendered per language.
  lines.push(`export const dynamicParams = ${consts.dynamic === '"force-dynamic"' ? "true" : open ? "true" : "false"};`);
  if (dynamicSegments && hasStaticParams) lines.push("export const generateStaticParams = m.generateStaticParams;");
  if (!client) lines.push("export const generateMetadata = m.generateMetadata;");
  lines.push("export default m.Page;", "");
  return lines.join("\n");
}

/** The share-image files Next reads from a route segment. */
const IMAGE = /^(opengraph-image|twitter-image)\.tsx?$/;

/**
 * A share image's key in the og-alt namespace: its route's folders joined by "_", "home" for the root
 * ("pokedex/games/[slug]" → "pokedex_games_slug"). tests/i18n-og-email.test.ts derives the same keys.
 */
const altKey = (relDir) => relDir.replace(/\[+(?:\.\.\.)?([^\]]+)\]+/g, "$1").replace(/[^A-Za-z0-9]+/g, "_") || "home";

/** The folder under a route where its share image in a language is served: /<lang>/<path>/share-image. */
const SHARE_IMAGE = "share-image";

/**
 * A share image in the language, as a route handler at /<lang>/<path>/share-image: the English image route's own
 * drawing, called with the language in its params (the card reads it there, see lib/og/i18n), drawn on request.
 * Not an opengraph-image file: Next only treats a file named exactly opengraph-image.tsx as one, so a
 * opengraph-image.locale.tsx was served without its image handler (a 405) at an address its pages' og:image
 * didn't even name. The pages point og:image here themselves (mirrorPage's `image`).
 */
function imageFile(rel, src) {
  const imp = `@/app/${rel.replace(/\.tsx?$/, "")}`;
  const { consts } = exportsOf(src);
  const lines = [HEADER, `// Source: src/app/${rel}`];
  lines.push(`import * as Source from "${imp}";`, `import { mirrorImageRoute } from "@/i18n/mirror";`, "");
  for (const key of COPIED) if (consts[key] !== undefined) lines.push(`export const ${key} = ${consts[key]};`);
  lines.push("export const GET = mirrorImageRoute(Source);", "");
  return lines.join("\n");
}

/** Every folder with a share image of its own ("" is the root's). */
const imageDirs = new Set(
  walk(APP)
    .filter((rel) => IMAGE.test(rel.split("/").pop()))
    .map((rel) => (dirname(rel) === "." ? "" : dirname(rel)))
);

/** The share image a page (or layout) in this folder shows (its own folder's, else the nearest one above it), as code. */
function imageOf(relDir) {
  for (let dir = relDir; ; dir = dirname(dir) === "." ? "" : dirname(dir)) {
    if (imageDirs.has(dir)) return `{ route: ${JSON.stringify(dir ? routeOf(dir) : "/")}, alt: ${JSON.stringify(altKey(dir))} }`;
    if (!dir) return null;
  }
}

function reexportFile(rel, src) {
  const imp = `@/app/${rel.replace(/\.tsx?$/, "")}`;
  const { consts, client } = exportsOf(src);
  const lines = [HEADER, `// Source: src/app/${rel}`];
  if (client) lines.push('"use client";', "");
  const meta = /^export (const metadata\b|(async )?function generateMetadata\b)/m.test(src);
  // A server layout renders apart from its page, so it sets the render's language itself (mirrorLayout).
  const layout = base(rel) === "layout.tsx" && !client;
  const helpers = [...(meta ? ["mirrorMetadata"] : []), ...(layout ? ["mirrorLayout"] : [])];
  if (helpers.length) lines.push(`import * as Source from "${imp}";`, `import { ${helpers.join(", ")} } from "@/i18n/mirror";`, "");
  // A layout's own title and description, pointed at the language's URL like a page's.
  const image = meta ? imageOf(dirname(rel) === "." ? "" : dirname(rel)) : null;
  if (meta) lines.push(`export const generateMetadata = mirrorMetadata(Source${image ? `, ${image}` : ""});`);
  lines.push(layout ? "export default mirrorLayout(Source);" : `export { default } from "${imp}";`);
  for (const key of COPIED) if (consts[key] !== undefined) lines.push(`export const ${key} = ${consts[key]};`);
  lines.push("");
  return lines.join("\n");
}

const wanted = new Map();
for (const rel of walk(APP)) {
  const base = rel.split("/").pop();
  if (!rel.includes("/") && OWN.has(base)) continue; // the root layout and 404 have the language's own versions
  const src = readFileSync(join(APP, rel), "utf8");
  if (base === "page.tsx") wanted.set(rel, pageFile(rel, src));
  else if (["layout.tsx", "loading.tsx", "not-found.tsx", "error.tsx"].includes(base)) wanted.set(rel, reexportFile(rel, src));
  else if (IMAGE.test(base)) wanted.set(`${dirname(rel) === "." ? "" : `${dirname(rel)}/`}${SHARE_IMAGE}/route.ts`, imageFile(rel, src));
}

const check = process.argv.includes("--check");
const existing = existsSync(OUT) ? walk(OUT).filter((r) => readFileSync(join(OUT, r), "utf8").startsWith(HEADER)) : [];
const wantedFiles = new Set([...wanted.keys()].map(out));
const problems = [];
for (const [rel, content] of wanted) {
  const file = join(OUT, out(rel));
  const now = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (now === content) continue;
  if (check) problems.push(`${now === null ? "missing" : "stale"}: ${file}`);
  else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
for (const rel of existing) {
  if (wantedFiles.has(rel)) continue;
  if (check) problems.push(`orphan: ${join(OUT, rel)}`);
  else rmSync(join(OUT, rel));
}
if (problems.length) {
  console.error(`src/app/[locale] is out of date (run \`npm run i18n:mirror\`):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
if (!check) console.log(`src/app/[locale]: ${wanted.size} files`);
